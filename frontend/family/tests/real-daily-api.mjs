// Real restricted API and PostgreSQL. Test-only credentials arrive on stdin, never in logs.
import { chromium, expect } from '@playwright/test';
import { preview } from 'vite';
import { writeFile } from 'node:fs/promises';

let input = '';
for await (const chunk of process.stdin) input += chunk;
const { apiOrigin, owner } = JSON.parse(input);
let server, browser, parent, step = 'preview', pageErrors = 0;
const button = (page, name) => page.getByRole('button', { name, exact: true });
const field = (page, name) => name === '作业日期' ? page.getByTestId('daily-day').getByLabel(name, { exact: true }) : page.getByLabel(name, { exact: true });
const navigate = (page, name) => page.getByRole('navigation', { name: '学习导航' }).getByRole('button', { name, exact: true }).click();
try {
  server = await preview({ configFile: false, logLevel: 'silent', build: { outDir: 'dist/build/h5' }, preview: {
    host: '127.0.0.1', port: 0, strictPort: true, proxy: { '/api/v1': { target: apiOrigin } },
  } });
  browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || 'chrome' });
  const origin = `http://127.0.0.1:${server.httpServer.address().port}`;
  const parentContext = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  const childContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
  parent = await parentContext.newPage();
  const child = await childContext.newPage();
  for (const page of [parent, child]) page.on('pageerror', () => { pageErrors++; });
  step = 'guardian login';
  await parent.goto(origin);
  await field(parent, '用户名').fill(owner.email);
  await field(parent, '登录密码').fill(owner.password);
  await button(parent, '登录').click();
  step = 'daily checklist and manual task';
  await navigate(parent, '每日作业');
  await field(parent, '作业日期').fill('2026-11-13');
  await button(parent, '新增').click();
  await field(parent, '作业内容').fill('阅读课文');
  await button(parent, '保存作业').click();
  await expect(parent.getByTestId('daily-item')).toHaveCount(1);
  await expect(parent.getByTestId('daily-day')).toContainText('清单待补充');
  step = 'image import';
  await button(parent, '导入作业截图').click();
  const png = await parent.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 200; canvas.height = 300;
    const ctx = canvas.getContext('2d'); ctx.fillStyle = 'white'; ctx.fillRect(0, 0, 200, 300);
    ctx.fillStyle = 'black'; ctx.fillText('Daily homework test fixture', 10, 30);
    return canvas.toDataURL('image/png').split(',')[1];
  });
  await field(parent, '选择作业清单图片').setInputFiles({ name: 'daily-fixture.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') });
  await field(parent, '来源说明').fill('浏览器验收作业来源');
  await field(parent, '目标日期（可选）').fill('2026-11-13');
  await button(parent, '开始识别清单').click();
  await expect(parent.getByTestId('import-candidate')).toHaveCount(2, { timeout: 20000 });
  await expect(field(parent, '第1项布置日期')).toHaveValue('');
  await expect(field(parent, '确认第1项布置日期')).not.toBeChecked();
  await field(parent, '第1项作业内容').fill('家长核对后的小册第16课');
  await field(parent, '第1项布置日期').fill('2026-11-13');
  await field(parent, '确认第1项布置日期').check();
  await button(parent, '第1项收入清单').click();
  await field(parent, '第2项布置日期').fill('2026-11-13');
  await field(parent, '确认第2项布置日期').check();
  await button(parent, '第2项收入清单').click();
  await button(parent, '保存识别草稿').click();
  step = 'draft persistence';
  await parent.reload();
  await navigate(parent, '每日作业');
  await button(parent, '导入作业截图').click();
  await parent.getByTestId('import-index').first().click();
  await expect(field(parent, '第1项作业内容')).toHaveValue('家长核对后的小册第16课');
  step = 'explicit draft publication';
  await button(parent, '发布已核对条目').click();
  await expect(parent.getByTestId('import-detail')).toContainText('已入清单');
  await button(parent, '返回清单').click();
  await field(parent, '作业日期').fill('2026-11-13');
  await expect(parent.getByTestId('daily-item')).toHaveCount(3);
  await expect(parent.getByTestId('daily-day')).toContainText('0/2');
  const written = parent.getByTestId('daily-item').filter({ hasText: '家长核对后的小册第16课' });
  await expect(written).toContainText('未标完成');
  await written.getByRole('button', { name: '查看记录与来源', exact: true }).click();
  await expect(parent.getByTestId('daily-source')).toHaveCount(1);
  await expect(parent.getByTestId('daily-source')).toContainText('浏览器验收作业来源');
  step = 'child pairing';
  await button(parent, '家长中心').click();
  await button(parent, '授权与设备').click();
  await button(parent, '生成孩子配对码').click();
  const code = await parent.getByTestId('pair-code').innerText();
  await child.goto(origin);
  await button(child, '连接孩子的学习设备').click();
  await field(child, '一次性配对码').fill(code);
  await button(child, '连接并开始学习').click();
  step = 'child progress is separate from verification';
  await navigate(child, '每日作业');
  await field(child, '作业日期').fill('2026-11-13');
  const childWritten = child.getByTestId('daily-item').filter({ hasText: '家长核对后的小册第16课' });
  await childWritten.getByRole('button', { name: '标记做完', exact: true }).click();
  await expect(childWritten).toContainText('已标完成');
  await expect(button(child, '新增')).toHaveCount(0);
  await expect(button(child, '家长确认完成')).toHaveCount(0);
  expect(await child.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  step = 'guardian verification and reload';
  await navigate(parent, '每日作业');
  await field(parent, '作业日期').fill('2026-11-13');
  await written.getByRole('button', { name: '查看记录与来源', exact: true }).click();
  await button(parent, '家长确认完成').click();
  await expect(written).toContainText('家长已核验');
  await parent.reload();
  await navigate(parent, '每日作业');
  await field(parent, '作业日期').fill('2026-11-13');
  await expect(parent.getByTestId('daily-item').filter({ hasText: '家长核对后的小册第16课' })).toContainText('家长已核验');
  step = 'explicit completeness and preparation denominator';
  await button(parent, '核对范围').click();
  for (const name of ['语文已有作业', '数学确认无作业', '英语确认无作业', '其他确认无作业']) await button(parent, name).click();
  await button(parent, '确认清单完整').click();
  await expect(parent.getByTestId('daily-day')).toContainText('清单已核对完整');
  await expect(parent.getByTestId('daily-day')).not.toContainText('今日作业已核对完成');
  const reading = parent.getByTestId('daily-item').filter({ hasText: '阅读课文' });
  await reading.getByRole('button', { name: '查看记录与来源', exact: true }).click();
  await button(parent, '家长确认完成').click();
  await expect(parent.getByTestId('daily-day')).toContainText('今日作业已核对完成');
  await expect(parent.getByTestId('daily-day')).toContainText('准备事项 0/1');
  step = 'empty day differs from confirmed no homework';
  await field(parent, '作业日期').fill('2026-11-14');
  await expect(parent.getByTestId('daily-day')).toContainText('未录入');
  await button(parent, '核对范围').click();
  for (const name of ['语文确认无作业', '数学确认无作业', '英语确认无作业', '其他确认无作业']) await button(parent, name).click();
  await button(parent, '确认清单完整').click();
  await expect(parent.getByTestId('daily-day')).toContainText('今日无作业');
  await expect(parent.getByTestId('daily-day')).not.toContainText('100%');
  await field(parent, '作业日期').fill('2026-11-13');
  step = 'mobile layout';
  await parent.setViewportSize({ width: 390, height: 844 });
  expect(await parent.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await parent.screenshot({ path: '/tmp/wizzy-daily-mobile.png', fullPage: true });
  await parent.setViewportSize({ width: 1280, height: 900 });
  await parent.screenshot({ path: '/tmp/wizzy-daily-desktop.png' });
  expect(pageErrors).toBe(0);
  console.log(JSON.stringify({ manual: 'passed', import: 'passed', child: 'passed', verification: 'passed', page_errors: pageErrors }));
} catch (error) {
  await writeFile('/tmp/wizzy-daily-browser-error.txt', String(error?.stack ?? error), { mode: 0o600 });
  if (parent) await parent.screenshot({ path: '/tmp/wizzy-daily-failure.png', fullPage: true }).catch(() => {});
  console.error(`Daily homework browser failed at ${step}. No credentials or source text logged.`);
  process.exitCode = 1;
} finally {
  if (browser) await browser.close();
  if (server) await new Promise(resolve => { server.httpServer.close(resolve); server.httpServer.closeAllConnections(); });
}
